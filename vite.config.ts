import { defineConfig, lazyPlugins } from "vite-plus";
import vue from "@vitejs/plugin-vue";
import VueRouter from "vue-router/vite";
import ui from "@nuxt/ui/vite";

const host = process.env.TAURI_DEV_HOST;

export default defineConfig(async () => ({
  plugins: lazyPlugins(() => [
    VueRouter({/* options */}),
    vue(),
    ui({
      colorMode: false,
      ui: {
        colors: {
          primary: "rose",
          neutral: "neutral",
        },
      },
    }),
  ]),

  optimizeDeps: {
    force: true,
  },

  build: {
    rollupOptions: {
      onLog(level, log, handler) {
        if (log.code === "INVALID_ANNOTATION" && log.id?.includes("@vueuse/core")) {
          return;
        }

        handler(level, log);
      },
    },
  },

  fmt: {
    ignorePatterns: [
      // Regenerated by vue-router and @nuxt/ui on every dev/build run.
      "auto-imports.d.ts",
      "components.d.ts",
      "typed-router.d.ts",
      // Rust/Tauri project and local SpacetimeDB demo data, not frontend sources.
      "src-tauri/**",
      "showcase-demo/**",
    ],
  },

  staged: {
    "*": "vp check --fix",
  },

  clearScreen: false,
  server: {
    port: 1420,
    strictPort: true,
    host: host || false,
    hmr: host
      ? {
          protocol: "ws",
          host,
          port: 1421,
        }
      : undefined,
    watch: {
      ignored: ["**/src-tauri/**"],
    },
  },
}));
